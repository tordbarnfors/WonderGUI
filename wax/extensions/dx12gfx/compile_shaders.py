#!/usr/bin/env python3
#
# Compiles the HLSL shaders in ../hlsl for DX12Backend, into wax_dx12shaders.cpp, which is checked
# in, so that DX12Backend has them compiled when it starts and building Wax doesn't need a shader
# compiler. Compiling them when first drawn with took up to 650 ms for one shader. Run it after
# changing a shader, on Windows, with FXC of the Windows SDK in the path, given with --fxc or
# where the SDK is usually installed:
#
#     python compile_shaders.py [--fxc path/to/fxc.exe]
#
# FXC only runs on Windows. After changing a shader elsewhere, wax_dx12shaders.cpp is left for
# someone on Windows to make anew. It says which sources it was made from, and
#
#     python compile_shaders.py --check
#
# tells if those are still the ones in ../hlsl, without FXC. CMakeLists.txt runs that when
# configuring, if there is a Python, and warns about shaders that are out of date.
#
# The shaders are those of VulkanBackend, listed in ../vulkangfx/compile_shaders.py, plus the
# mipmap shaders, which VulkanBackend doesn't need. Each is a few files of ../hlsl put one after
# the other, see ../hlsl/README.md. Pixel shaders are compiled twice, the second time with
# WAX_DUAL_SOURCE for pipelines that blend with a second color.
#
# Options:
#
#   /O3                     As DX12Backend compiled them in release builds.
#   /Ges                    Strict mode.
#   /WX                     Warnings are errors.
#   /all_resources_bound    Lets FXC leave out checks for resources that aren't bound.

import argparse
import glob
import hashlib
import importlib.util
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
HLSL = os.path.join(HERE, '..', 'hlsl')
OUTPUT = os.path.join(HERE, 'wax_dx12shaders.cpp')

# The shader lists of VulkanBackend, so there is one list to keep in step with the HLSL.

spec = importlib.util.spec_from_file_location('vulkan_shaders', os.path.join(HERE, '..', 'vulkangfx', 'compile_shaders.py'))
vulkan_shaders = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vulkan_shaders)

VERTEX_SHADERS = vulkan_shaders.VERTEX_SHADERS + [('mipmapVS', ['vs_mipmap.hlsl'])]
PIXEL_SHADERS = vulkan_shaders.PIXEL_SHADERS
MIPMAP_PIXEL_SHADER = ('mipmapPS', ['ps_mipmap.hlsl'])

FXC_OPTIONS = ['/nologo', '/E', 'main', '/O3', '/Ges', '/WX', '/all_resources_bound']

