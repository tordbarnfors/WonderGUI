#!/usr/bin/env python3
#
# Turns the HLSL shaders in ../hlsl into MSL for MetalBackend, in wax_metalshaders.mm, which is
# checked in, so building Wax doesn't need a shader compiler. DXC compiles each shader to SPIR-V
# and SPIRV-Cross (https://github.com/KhronosGroup/SPIRV-Cross) turns that into MSL, which Metal
# compiles when MetalBackend first needs the shader. Run it after changing a shader, with DXC and
# spirv-cross in the path or given with --dxc and --spirv-cross:
#
#     python3 compile_shaders.py [--dxc path/to/dxc] [--spirv-cross path/to/spirv-cross]
#
# The shaders are those of VulkanBackend, listed in ../vulkangfx/compile_shaders.py, plus the
# mipmap shaders, which VulkanBackend doesn't need. Pixel shaders are compiled twice, the second
# time with WAX_DUAL_SOURCE for pipelines that blend with a second color. All are compiled as
# HLSL 2018, see ../hlsl/README.md.
#
# Where things end up in Metal, see MetalBackend:
#
#   Constants       The push constants of constants.hlsl, buffer 0 of both stages.
#   t0-t4           Buffers 1-5 (-fvk-t-shift 1 0, then --msl-decoration-binding), the blit source
#                   (t2) texture 3.
#   s0              Sampler 0.
#   Vertex inputs   Attributes 0-3 in the order of ../hlsl/README.md, from the vertex buffer that
#                   MetalBackend puts at the index it says.
#
# Unlike for VulkanBackend, y isn't flipped: clip space points up in Metal as in D3D. MSL 2.3
# (macOS 11) is needed for discard to have the meaning it has in D3D, where pixels that are
# discarded still take part in derivatives.

import argparse
import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
HLSL = os.path.join(HERE, '..', 'hlsl')
OUTPUT = os.path.join(HERE, 'wax_metalshaders.mm')

# The shader lists of VulkanBackend, so there is one list to keep in step with the HLSL.

spec = importlib.util.spec_from_file_location('vulkan_shaders', os.path.join(HERE, '..', 'vulkangfx', 'compile_shaders.py'))
vulkan_shaders = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vulkan_shaders)

VERTEX_SHADERS = vulkan_shaders.VERTEX_SHADERS + [('mipmapVS', ['vs_mipmap.hlsl'])]
PIXEL_SHADERS = vulkan_shaders.PIXEL_SHADERS
MIPMAP_PIXEL_SHADER = ('mipmapPS', ['ps_mipmap.hlsl'])

DXC_OPTIONS = ['-nologo', '-HV', '2018', '-spirv', '-fspv-target-env=vulkan1.3', '-fvk-t-shift', '1', '0', '-O3', '-E', 'main']
SPIRV_CROSS_OPTIONS = ['--msl', '--msl-version', '20300', '--msl-decoration-binding']

