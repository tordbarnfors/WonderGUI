"				  constant vector_float4  *pColor [[buffer(1)]],\n"
"				  constant vector_float4  *pExtras [[buffer(2)]],\n"
"				  constant Uniform * pUniform[[buffer(3)]])\n"
"{\n"
"	ShapeFragInput out;\n"
