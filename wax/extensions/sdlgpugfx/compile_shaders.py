def run(cmd, what):
	try:
		result = subprocess.run(cmd, capture_output=True, text=True)
	except OSError as e:
		sys.stderr.write('%s: could not run %s: %s\n' % (what, cmd[0], e))
		sys.exit(1)

	if result.returncode != 0:
		sys.stderr.write('%s failed:\n%s%s' % (what, result.stdout, result.stderr))
		sys.exit(1)


def source(files):
	text = ''
	for part in files:
		with open(os.path.join(HLSL, part)) as p:
			text += '#line 1 "%s"\n' % part
			text += p.read()
			text += '\n'
	return text


# What a preprocessed shader binds, in the slots SDL_GPU has for it.

class Layout:
	def __init__(self, text):
		self.textures = []			# Registers, in slot order.
		self.samplers = []
		self.storage = []
		self.uniforms = []

		for kind, name, reg, number in DECLARATION.findall(text):
			number = int(number)

			if reg == 'b':
				self.uniforms.append(number)
			elif reg == 's':
				self.samplers.append(number)
			elif kind.startswith('Texture'):
				self.textures.append(number)
			elif kind.startswith('StructuredBuffer'):
				self.storage.append(number)
			else:
				sys.exit('Register %s%d of %s is of a kind SdlGpuBackend has no slot for: %s' % (reg, number, name, kind))

		for regs in (self.textures, self.samplers, self.storage, self.uniforms):
			regs.sort()

		# Samplers go with the sampled texture of the same slot, uniform buffers by number.

		if self.textures not in ([], [2]) or self.samplers not in ([], [0]):
			sys.exit('SdlGpuBackend only has the blit source (t2, s0) as texture.')

		if self.uniforms != list(range(len(self.uniforms))):
			sys.exit('Uniform buffers must be b0 and on, without gaps.')

	# Moves the registers to their slots. Storage buffers come after the textures, or for Metal
	# after the uniform buffers, which share the buffer slots with them there.

	def apply(self, text, stage, bMetal):
		resourceSpace, uniformSpace = SPACES[stage]
		storageBase = len(self.uniforms) if bMetal else len(self.textures)

		def move(match):
			kind, name, reg, number = match.groups()
			number = int(number)

			if reg == 'b':
				slot, space = number, uniformSpace
			elif reg == 's':
				slot, space = self.samplers.index(number), resourceSpace
			elif kind.startswith('Texture'):
				slot, space = self.textures.index(number), resourceSpace
			else:
				slot, space = storageBase + self.storage.index(number), resourceSpace

			return '%s %s : register(%s%d, space%d)' % (kind, name, reg, slot, space)

		return DECLARATION.sub(move, text)


# Vertex inputs named as SDL_GPU names them for D3D12.

def rename_vertex_inputs(text):
	match = re.search(r'struct\s+VS_INPUT\s*\{(.*?)\};', text, re.DOTALL)
	if not match:
		return text

	body = match.group(1)
	for i, semantic in enumerate(VERTEX_INPUTS):
		body = re.sub(r':\s*%s\b' % semantic, ': WAX_INPUT_%d' % i, body)
	body = body.replace('WAX_INPUT_', 'TEXCOORD')

	return text[:match.start(1)] + body + text[match.end(1):]


def preprocess(args, tmpdir, name, text, defines, bSpirv):
	src = os.path.join(tmpdir, name + '.hlsl')
	out = os.path.join(tmpdir, name + ('.spirv' if bSpirv else '.dxil') + '.pp.hlsl')

	with open(src, 'w') as f:
		f.write(text)

	run([args.dxc] + COMMON_OPTIONS + (['-spirv'] if bSpirv else []) + defines + ['-P', '-Fi', out, src], 'Preprocessing ' + name)

	with open(out) as f:
		return f.read()


def compile_one(args, tmpdir, name, text, profile, options, suffix):
	src = os.path.join(tmpdir, name + suffix + '.hlsl')
	out = os.path.join(tmpdir, name + suffix + '.bin')

	with open(src, 'w') as f:
		f.write(text)

	run([args.dxc] + COMMON_OPTIONS + options + ['-T', profile, src, '-Fo', out], 'Compiling %s (%s)' % (name, suffix))

	with open(out, 'rb') as f:
		return f.read()


def compile_shader(args, tmpdir, name, files, stage, defines):
	profile = stage + '_6_0'
	text = source(files)

	# SPIR-V, and SPIR-V with the slots of Metal for SPIRV-Cross.

	spirvText = preprocess(args, tmpdir, name, text, defines, True)
	layout = Layout(spirvText)

	spirv = compile_one(args, tmpdir, name, layout.apply(spirvText, stage, False), profile, SPIRV_OPTIONS, '.vk')
	assert len(spirv) % 4 == 0

	metalSpirv = os.path.join(tmpdir, name + '.mtl.bin')
	with open(metalSpirv, 'wb') as f:
		f.write(compile_one(args, tmpdir, name, layout.apply(spirvText, stage, True), profile, SPIRV_OPTIONS, '.mtl'))

	msl = os.path.join(tmpdir, name + '.metal')
	run([args.spirv_cross] + SPIRV_CROSS_OPTIONS + [metalSpirv, '--output', msl], 'Cross-compiling ' + name)

	with open(msl, 'rb') as f:
		mslData = f.read()

	# DXIL, from the HLSL as preprocessed without __spirv__.

	dxilText = preprocess(args, tmpdir, name, text, defines, False)

	if Layout(dxilText).__dict__ != layout.__dict__:
		sys.exit('%s binds other registers for DXIL than for SPIR-V.' % name)

	dxilText = layout.apply(dxilText, stage, False)
	if stage == 'vs':
		dxilText = rename_vertex_inputs(dxilText)

	dxil = compile_one(args, tmpdir, name, dxilText, profile, DXIL_OPTIONS, '.dx')

	if dxil[4:20] == bytes(16):
		sys.exit('DXC left the DXIL of %s unsigned, which D3D12 refuses. It signs it with libdxil (dxil.dll), which must be next to it.' % name)

	return { 'name': name, 'stage': stage, 'layout': layout, 'spv': spirv, 'dxil': dxil, 'msl': mslData }


STORAGE_NAMES = { 0: 'Colors', 1: 'Extras', 3: 'EdgemapOrPalette', 4: 'WarpVertices' }


def table_entry(shader):
	layout = shader['layout']

	storage = ', '.join('Resource::' + STORAGE_NAMES[reg] for reg in layout.storage)
	if not storage:
		storage = 'Resource::None'

	return '\t\t{ "%s", %s, %d, %d, { %s }, %d },\n' % (
		shader['name'], 'Stage::Vertex' if shader['stage'] == 'vs' else 'Stage::Pixel',
		len(layout.textures), len(layout.storage), storage, len(layout.uniforms))


def main():
	parser = argparse.ArgumentParser(description='Compiles the HLSL shaders of SdlGpuBackend to SPIR-V, DXIL and MSL.')
	parser.add_argument('--dxc', default=shutil.which('dxc') or 'dxc', help='DXC executable')
	parser.add_argument('--spirv-cross', default=shutil.which('spirv-cross') or 'spirv-cross', help='SPIRV-Cross executable')
	args = parser.parse_args()

	shaders = []

	with tempfile.TemporaryDirectory() as tmpdir:
		for name, files in VERTEX_SHADERS:
			shaders.append(compile_shader(args, tmpdir, name, files, 'vs', []))

		for name, files in PIXEL_SHADERS:
			files = files[:-1] + ['sdlgpu.hlsl'] + files[-1:]			# In front of the pixel shader itself.
			shaders.append(compile_shader(args, tmpdir, name, files, 'ps', []))
			shaders.append(compile_shader(args, tmpdir, name + 'Dual', files + ['sdlgpu_dual.hlsl'], 'ps',
										  ['-D', 'WAX_DUAL_SOURCE=1', '-D', 'main=waxMain']))

	os.makedirs(OUTPUT, exist_ok=True)

	for old in os.listdir(OUTPUT):
		if os.path.splitext(old)[1] in ('.spv', '.dxil', '.msl'):
			os.remove(os.path.join(OUTPUT, old))

	for shader in shaders:
		for ext in ('spv', 'dxil', 'msl'):
			with open(os.path.join(OUTPUT, shader['name'] + '.' + ext), 'wb') as f:
				f.write(shader[ext])

	with open(TABLE, 'w', newline='\n') as f:
		f.write(HEADER)
		for shader in shaders:
			f.write(table_entry(shader))
		f.write(FOOTER)

	print('Wrote %d shaders to %s' % (len(shaders), OUTPUT))


if __name__ == '__main__':
	main()
