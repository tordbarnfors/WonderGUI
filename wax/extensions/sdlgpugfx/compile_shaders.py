#!/usr/bin/env python3
#
# Compiles the HLSL shaders in ../hlsl for SdlGpuBackend, for each kind of device SDL_GPU can
# have, into shaders/, which is checked in, so building Wax doesn't need a shader compiler:
#
#   shaders/<name>.spv     SPIR-V, for Vulkan.
#   shaders/<name>.dxil    DXIL (shader model 6.0), for D3D12. DXC signs it when libdxil (dxil.dll
#                          on Windows) is next to it, which D3D12 needs.
#   shaders/<name>.msl     MSL 2.3, for Metal, from SPIR-V by SPIRV-Cross.
#
# CMakeLists.txt turns those a platform can use into arrays in the build directory. What each
# shader binds is written to wax_sdlgpushaders.cpp, also checked in. Run it after changing a
# shader, with DXC (https://github.com/microsoft/DirectXShaderCompiler) and spirv-cross in the
# path or given with --dxc and --spirv-cross:
#
#     python3 compile_shaders.py [--dxc path/to/dxc] [--spirv-cross path/to/spirv-cross]
#
# The shaders are those of VulkanBackend, listed in ../vulkangfx/compile_shaders.py, compiled with
# WAX_SDLGPU, which gives them the constants as cbuffers (SDL_GPU has no push constants) and
# ../hlsl/sdlgpu.hlsl for the texels of blit sources. SDL_GPU can't blend with a second color, so
# the Dual pixel shaders get ../hlsl/sdlgpu_dual.hlsl after them, which outputs what SdlGpuBackend
# blends with instead. All are compiled as HLSL 2018, see ../hlsl/README.md.
#
# SDL_GPU binds resources by slots of their own for each stage and kind, counted from 0 in the
# order SDL_CreateGPUShader() describes. So each shader is preprocessed, its registers are moved
# to those slots and it is compiled from that:
#
#   b0-b3       Uniform buffers 0-3: CanvasInfo, PixelInfo, WarpInfo and SdlOutputInfo.
#   t2, s0      The blit source, sampled texture 0 and its sampler.
#   t0, t1...   The storage buffers the shader has, in the order of their registers, which
#               wax_sdlgpushaders.cpp lists for SdlGpuBackend to bind them by.
#
# Vertex inputs are TEXCOORD0-3 in DXIL, which is what SDL_GPU names them for D3D12, and get their
# locations in the order they are declared elsewhere, see ../hlsl/README.md. y isn't flipped for
# Vulkan, SDL_GPU flips the viewport to give all its devices the clip space of D3D.

import argparse
import importlib.util
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
HLSL = os.path.join(HERE, '..', 'hlsl')
OUTPUT = os.path.join(HERE, 'shaders')
TABLE = os.path.join(HERE, 'wax_sdlgpushaders.cpp')

# The shader lists of VulkanBackend, so there is one list to keep in step with the HLSL.

spec = importlib.util.spec_from_file_location('vulkan_shaders', os.path.join(HERE, '..', 'vulkangfx', 'compile_shaders.py'))
vulkan_shaders = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vulkan_shaders)

VERTEX_SHADERS = vulkan_shaders.VERTEX_SHADERS
PIXEL_SHADERS = vulkan_shaders.PIXEL_SHADERS

COMMON_OPTIONS = ['-nologo', '-HV', '2018', '-E', 'main', '-D', 'WAX_SDLGPU=1']
SPIRV_OPTIONS = ['-spirv', '-fspv-target-env=vulkan1.0', '-O3']
DXIL_OPTIONS = ['-O3']
SPIRV_CROSS_OPTIONS = ['--msl', '--msl-version', '20300', '--msl-decoration-binding']

# Register spaces of SDL_GPU for D3D12, and descriptor sets for Vulkan: resources, uniforms.

SPACES = { 'vs': (0, 1), 'ps': (2, 3) }

# Semantics of the vertex inputs in DXIL, in the order of ../hlsl/README.md.

VERTEX_INPUTS = ['POSITION', 'COLOROFS', 'EXTRASOFS', 'TEXCOORD0']

DECLARATION = re.compile(r'(\w+(?:\s*<\s*\w+\s*>)?)\s+(\w+)\s*:\s*register\(\s*([tsb])(\d+)\s*\)')

