def build_preview_html(kit, atlas, manifest, density):
    import base64
    import io

    def b64_crop(meta):
        x, y = round(meta["atlas_x_pts"] * density), round(meta["atlas_y_pts"] * density)
        w, h = round(meta["size_pts"][0] * density), round(meta["size_pts"][1] * density)
        n = len(meta["states"])
        if meta["axis"] == "x":
            full = atlas.crop((x, y, x + n * w + (n - 1) * round(meta["spacing_pts"] * density), y + h))
        elif meta["axis"] == "y":
            full = atlas.crop((x, y, x + w, y + n * h + (n - 1) * round(meta["spacing_pts"] * density)))
        else:
            full = atlas.crop((x, y, x + w, y + h))
        buf = io.BytesIO()
        full.save(buf, "PNG")
        return base64.b64encode(buf.getvalue()).decode()

    css = """
    body{font-family:sans-serif;background:#eef0f3;padding:20px;color:#222}
    h2{font-size:13px;margin:22px 0 6px}
    .meta{font-size:11px;color:#667;margin-bottom:6px}
    .ok{color:#186a3b}
    .row{display:flex;gap:14px;align-items:center;flex-wrap:wrap;margin-bottom:8px}
    .chip{image-rendering:pixelated;border:1px solid #ccc;background:
      repeating-conic-gradient(#ddd 0% 25%, #fff 0% 50%) 50% / 12px 12px}
    .demo{position:relative}
    .demo img{display:block;width:100%;height:100%;image-rendering:pixelated}
    .content{position:absolute;display:flex;align-items:center;justify-content:flex-start;
      outline:1px dashed rgba(0,0,0,.35);color:#08306b;font-weight:600;font-size:12px}
    """
    html = [f'<!doctype html><html><head><meta charset="utf-8"><title>{kit} preview</title><style>{css}</style></head><body>']
    html.append(f"<h1>{kit} widgetkit preview</h1>")

    zoom = 4          # CSS px per pt in this preview

    for meta in manifest:
        b64 = b64_crop(meta)
        name = meta["name"]
        html.append(f"<h2>{name}</h2>")
        rigid_note = ""
        for rp in rigid_parts(meta):
            rigid_note += (f" &middot; <span class='ok'>rigidPart{rp['axis'].upper()} "
                           f"{rp['begin_pts']}..{rp['begin_pts'] + rp['length_pts']}pts "
                           f"({rp['sections']}) held rigid below</span>")
        html.append(f"<div class='meta'>states: {', '.join(meta['states'])} &middot; "
                     f"size_pts: {meta['size_pts']} &middot; frame_pts: {meta['frame_pts']} &middot; "
                     f"padding_pts: {meta['padding_pts']}{rigid_note}</div>")
        html.append("<div class='row'>")
        html.append(f"<img class='chip' style='width:auto;height:{meta['size_pts'][1]*zoom if meta['axis']!='y' else meta['size_pts'][1]*len(meta['states'])*zoom}px' "
                     f"src='data:image/png;base64,{b64}'>")

        # Any framed block gets stretch demos, including single-state panels
        # (axis "single"). Those were excluded before, which is precisely why
        # Plate/Canvas/Window went so long with no frame at all: the preview
        # never showed them stretched, so the smeared borders never appeared.
        if meta["frame_pts"] is not None:
            t, r, b, l = border_tuple(meta["frame_pts"])
            w_pts, h_pts = meta["size_pts"]
            frame_px = tuple(round(v * density) for v in (t, r, b, l))

            block = atlas.crop((round(meta["atlas_x_pts"] * density),
                                round(meta["atlas_y_pts"] * density),
                                round((meta["atlas_x_pts"] + w_pts) * density),
                                round((meta["atlas_y_pts"] + h_pts) * density)))
            rigids = [rebase_rigid(rp, frame_px, block.size, density)
                      for rp in rigid_parts(meta)]

            # Only demo an axis that has stretchable material left over. A
            # horizontal scrollbar handle's frame spans its full height by
            # design (top 8 + bottom 8 of a 16pt block), so a "taller" demo
            # would show a legitimately empty band and read as a defect.
            stretch_x, stretch_y = (l + r) < w_pts, (t + b) < h_pts
            if stretch_x and stretch_y:
                # First demo shows the widget stretched along the axis it is
                # actually used on, so it reads as normal usage; the second
                # stretches both, to stress the other axis and any rigid part
                # pinned on it. A split bar grows along its length only, so
                # showing it 2x WIDE first was misleading.
                primary = meta.get("stretch_axis") or "x"
                if primary == "y":
                    sizes = [(w_pts, h_pts * 2), (w_pts * 2, h_pts * 3)]
                else:
                    sizes = [(w_pts * 2, h_pts), (w_pts * 3, h_pts * 2)]
            elif stretch_x:
                sizes = [(w_pts * 2, h_pts), (w_pts * 4, h_pts)]
            elif stretch_y:
                sizes = [(w_pts, h_pts * 2), (w_pts, h_pts * 4)]
            else:
                sizes = []

            pt, pr, pb, pl = border_tuple(meta["padding_pts"]) or (0, 0, 0, 0)
            for w, h in sizes:
                img = simulate_stretch(block, frame_px,
                                       (round(w * density), round(h * density)), rigids)
                buf = io.BytesIO()
                img.save(buf, "PNG")
                d64 = base64.b64encode(buf.getvalue()).decode()
                # The dashed box is the content rect (size minus padding) --
                # it shows at a glance whether text would collide with an
                # inset glyph such as the select box's arrow.
                html.append(
                    f"<div class='demo' style='width:{w*zoom}px;height:{h*zoom}px' "
                    f"title='{name} stretched to {w}x{h} pts'>"
                    f"<img src='data:image/png;base64,{d64}'>"
                    f"<div class='content' style='top:{pt*zoom}px;right:{pr*zoom}px;"
                    f"bottom:{pb*zoom}px;left:{pl*zoom}px'>Aa</div></div>")
        html.append("</div>")

    html.append("</body></html>")
    return "\n".join(html)


