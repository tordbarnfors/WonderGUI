def cmd_render(kit, names, force, density):
    kit_dir = KIT_ROOT / kit
    palette = yaml.safe_load((kit_dir / "palette.yaml").read_text())
    specs_dir = kit_dir / "specs"
    parts_dir = kit_dir / "parts"
    parts_dir.mkdir(exist_ok=True)

    all_specs = {p.stem: yaml.safe_load(p.read_text()) for p in sorted(specs_dir.glob("*.yaml"))}

    if names:
        missing = [n for n in names if n not in all_specs]
        if missing:
            raise SystemExit(f"No spec for: {', '.join(missing)}")
        targets = names
    else:
        # No names given: default target set is every spec. --force here means
        # "regenerate everything"; without it, only widgets missing a part are touched.
        targets = list(all_specs)

    skipped = []
    rendered = []
    for name in targets:
        png_path = parts_dir / f"{name}.png"
        if png_path.exists() and not force:
            skipped.append(name)
            continue
        spec = all_specs[name]
        img, meta = render_widget(name, spec, palette, density)
        img.save(png_path)
        (parts_dir / f"{name}.json").write_text(json.dumps(meta, indent=2))
        rendered.append(name)

    print(f"Rendered: {', '.join(rendered) if rendered else '(none)'}")
    if skipped:
        print(f"Skipped (already exist, use --force to overwrite): {', '.join(skipped)}")


