#!/usr/bin/env python3
"""
widgetkit-src build tool.

Usage:
  python3 build.py render <kit> [widget ...] [--force]
      Render specs/*.yaml (or just the named widgets) into parts/<name>.png
      + parts/<name>.json. Only touches widgets you name, or ones with no
      parts/ file yet -- pass --force to also overwrite named widgets that
      already have rendered parts.

  python3 build.py pack <kit>
      Read every parts/*.png + .json pair, pack them into the atlas,
      regenerate the header's two generated sections (the Colors:: constants,
      from palette.yaml's exported_colors, and the Skins::), rebuild
      preview.html, and copy the atlas + header to their real repo
      locations (resources/, src/widgetkits/).

Directory layout expected (kit_dir = widgetkit-src/<kit>/):
  palette.yaml
  specs/<Name>.yaml
  parts/<Name>.png, parts/<Name>.json      (generated by `render`)
  header_shell.h                            (hand-maintained)
  preview.html, <kit>_skinblocks.png, wg_<kit>.h   (generated by `pack`)
"""
