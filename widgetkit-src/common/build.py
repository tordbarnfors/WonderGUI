def border_tuple(v):
    """Normalize a frame/padding value (int, or [t,r,b,l]) to a 4-tuple, or None."""
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return (v, v, v, v)
    return tuple(v)


def pack_atlas(kit):
    kit_dir = KIT_ROOT / kit
    parts_dir = kit_dir / "parts"
    parts = []
    for json_path in sorted(parts_dir.glob("*.json")):
        meta = json.loads(json_path.read_text())
        png_path = parts_dir / f"{meta['name']}.png"
        img = Image.open(png_path)
        parts.append((meta, img))

    if not parts:
        raise SystemExit("No parts/ found -- run `render` first.")

    # A part whose spec is gone still gets packed and still generates its
    # Skins:: entry, so deleting only the spec leaves a stale skin in the
    # header that refers to a member nobody declares any more. Hand-authored
    # parts with no spec are legitimate, so warn rather than fail.
    spec_names = {p.stem for p in (kit_dir / "specs").glob("*.yaml")}
    orphans = [m["name"] for m, _ in parts if m["name"] not in spec_names]
    if orphans:
        print(f"warning: parts with no spec in specs/: {', '.join(sorted(orphans))}\n"
              f"         they are still packed and still generate Skins:: entries -- "
              f"delete parts/<name>.png and .json if that is not what you want.",
              file=sys.stderr)

    density = parts[0][0]["density"]
    for meta, _ in parts:
        if meta["density"] != density:
            raise SystemExit(f"Density mismatch: {meta['name']} was rendered at {meta['density']}x, "
                              f"expected {density}x. Re-render everything at one consistent density.")

    ATLAS_WIDTH = 640
    GUTTER = T.px(1, density)
    cursor_x, row_y, row_h = GUTTER, GUTTER, 0
    positions = []

    for meta, img in parts:
        w, h = img.size
        if cursor_x + w + GUTTER > ATLAS_WIDTH:
            row_y += row_h + GUTTER
            cursor_x = GUTTER
            row_h = 0
        positions.append((cursor_x, row_y))
        cursor_x += w + GUTTER
        row_h = max(row_h, h)

    atlas_h = row_y + row_h + GUTTER
    atlas = Image.new("RGBA", (ATLAS_WIDTH, atlas_h), (0, 0, 0, 0))
    manifest = []
    for (meta, img), (x, y) in zip(parts, positions):
        atlas.alpha_composite(img, (x, y))
        manifest.append(dict(meta, atlas_x_pts=round(x / density), atlas_y_pts=round(y / density)))

    return atlas, manifest, density


# Widgets whose skin pointer isn't Skins::<Name> -- everything else defaults to that.
CPP_TARGET_OVERRIDES = {
    "PlusMinusToggle": "_pPlusMinusToggleSkin",
}


def fmt_border(v):
    if v is None:
        return None
    t, r, b, l = border_tuple(v)
    if t == r == b == l:
        return str(int(t))
    return f"{{ {int(t)},{int(r)},{int(b)},{int(l)} }}"


AXIS_CPP = {"x": "Axis::X", "y": "Axis::Y"}


def gen_skin_block(entry):
    target = CPP_TARGET_OVERRIDES.get(entry["name"], f"Skins::{entry['name']}")
    x, y = entry["atlas_x_pts"], entry["atlas_y_pts"]
    w, h = entry["size_pts"]
    lines = [f"\t\t{target} = BlockSkin::create(WGBP(BlockSkin,",
             f"\t\t\t_.surface = pSkinBlocks,",
             f"\t\t\t_.firstBlock = {{ {int(x)},{int(y)},{int(w)},{int(h)} }},"]

    if entry["axis"] in ("x", "y"):
        lines.append(f"\t\t\t_.axis = {AXIS_CPP[entry['axis']]},")
        lines.append(f"\t\t\t_.blockSpacing = {int(entry['spacing_pts'])},")

    frame = fmt_border(entry["frame_pts"])
    if frame is not None:
        lines.append(f"\t\t\t_.frame = {frame},")
    padding = fmt_border(entry["padding_pts"])
    if padding is not None:
        lines.append(f"\t\t\t_.padding = {padding},")

    for rp in rigid_parts(entry):
        field = "rigidPartX" if rp["axis"] == "x" else "rigidPartY"
        enum = "YSections" if rp["axis"] == "x" else "XSections"
        # `sections` may name several, e.g. "Top|Bottom". Qualify each one:
        # "YSections::Top|Bottom" is not valid C++, and both enums define
        # operator| (plus an All) in wg_gfxtypes.h.
        sections = " | ".join(f"{enum}::{s.strip()}" for s in str(rp["sections"]).split("|"))
        lines.append(f"\t\t\t_.{field} = {{{int(rp['begin_pts'])},{int(rp['length_pts'])},{sections}}},")

    states = entry["states"]
    if not (len(states) == 1 and states[0] == "Default"):
        states_cpp = ", ".join(f"State::{s}" for s in states)
        lines.append(f"\t\t\t_.states = {{ {states_cpp} }}")
    else:
        lines[-1] = lines[-1].rstrip(",")  # drop trailing comma on last real field

    # Clean up: ensure no trailing comma before closing paren
    if lines[-1].endswith(","):
        lines[-1] = lines[-1][:-1]

    lines.append("\t\t));")
    return "\n".join(lines)


BEGIN_MARKER = "// >>> BEGIN GENERATED SKINS <<<"
END_MARKER = "// >>> END GENERATED SKINS <<<"

COLORS_BEGIN = "// >>> BEGIN GENERATED COLORS <<<"
COLORS_END = "// >>> END GENERATED COLORS <<<"


def _marker_line_matches(marker, shell):
    """Find occurrences of `marker` appearing as its OWN line (only leading/
    trailing whitespace beside it). A plain substring search is not safe here:
    if any hand-written prose elsewhere in header_shell.h happens to mention
    the marker text (e.g. explaining what the markers do), a naive
    str.split() would silently splice at the wrong spot instead of the real
    marker, quietly discarding everything in between. Returns a list of
    re.Match objects, in order."""
    pattern = re.compile(r"^[ \t]*" + re.escape(marker) + r"[ \t]*$", re.MULTILINE)
    return list(pattern.finditer(shell))


def gen_colors(kit, palette, density):
    """Emit the Colors:: constants declared under `exported_colors` in
    palette.yaml.

    These were hand-written C++ while the gradients lived in YAML, with
    nothing tying the two together -- so every palette change silently
    invalidated them, and Colors::Plate drifted to the gradient's TOP colour
    while the bitmap's middle was 14 levels darker. Anything using it to sit
    flush against a Plate was visibly off.

    `center_of` is the important form: it MEASURES the centre pixel of a
    rendered part, so the constant is whatever the bitmap actually is, however
    the recipe draws it. The others are conveniences for colours a bitmap
    doesn't define.
    """
    parts_dir = KIT_ROOT / kit / "parts"
    lines = []
    for name, src in (palette.get("exported_colors") or {}).items():
        if "center_of" in src:
            part = src["center_of"]
            meta = json.loads((parts_dir / f"{part}.json").read_text())
            img = Image.open(parts_dir / f"{part}.png").convert("RGBA")
            d = meta.get("density", density)
            w, h = (round(v * d) for v in meta["size_pts"])
            rgb = img.crop((0, 0, w, h)).getpixel((w // 2, h // 2))[:3]
            auto = f"measured: centre pixel of parts/{part}.png"
        elif "border_of" in src:
            rgb = tuple(palette[src["border_of"]]["border"][:3])
            auto = f"palette: {src['border_of']}.border"
        elif "top_of" in src or "bottom_of" in src:
            key = "top_of" if "top_of" in src else "bottom_of"
            rgb = tuple(palette[src[key]][key[:-3]][:3])
            auto = f"palette: {src[key]}.{key[:-3]}"
        elif "rgb" in src:
            rgb = tuple(src["rgb"])
            auto = ""
        else:
            raise SystemExit(f"exported_colors[{name}]: need one of "
                             f"center_of / border_of / top_of / bottom_of / rgb")
        note = src.get("note", auto)
        if src.get("comment"):
            if lines:
                lines.append("")
            for cl in src["comment"].rstrip("\n").split("\n"):
                lines.append(f"\t\t// {cl}".rstrip())
        decl = f"\t\tinline const Color\t{name} = Color({rgb[0]},{rgb[1]},{rgb[2]});"
        lines.append(f"{decl}\t\t// {note}" if note else decl)
    return "\n".join(lines)


def _splice(shell, begin, end, body):
    """Replace the region between the `begin` and `end` marker lines with
    `body`, keeping the marker lines themselves."""
    begin_matches = _marker_line_matches(begin, shell)
    end_matches = _marker_line_matches(end, shell)

    if len(begin_matches) != 1 or len(end_matches) != 1:
        raise SystemExit(
            f"header_shell.h must contain exactly one {begin!r} line "
            f"and one {end!r} line (found {len(begin_matches)} / "
            f"{len(end_matches)}). If these strings appear elsewhere too "
            f"(e.g. in an explanatory comment), reword that mention so it "
            f"isn't a standalone line matching the marker exactly."
        )
    if begin_matches[0].start() >= end_matches[0].start():
        raise SystemExit(f"header_shell.h: {begin!r} must come before {end!r}")

    # post starts at the END marker's own line start (the match includes that
    # line's leading whitespace), so its original indentation is preserved and
    # nothing is added in front of it.
    pre = shell[: begin_matches[0].end()]
    post = shell[end_matches[0].start() :]
    return f"{pre}\n{body}\n{post}"


def generate_header(kit, manifest, palette, density):
    kit_dir = KIT_ROOT / kit
    shell = (kit_dir / "header_shell.h").read_text()

    shell = _splice(shell, COLORS_BEGIN, COLORS_END, gen_colors(kit, palette, density))
    shell = _splice(shell, BEGIN_MARKER, END_MARKER,
                    "\n\n".join(gen_skin_block(e) for e in manifest))
    return shell


# ---------------------------------------------------------------------------
# Faithful port of GfxDeviceGen1::blitNinePatch, used to render the preview's
# stretch demos. CSS border-image cannot express rigidPartX/Y at all, so
# simulating the real algorithm here is the only way the preview can show what
# the widget will actually look like when stretched.
# ---------------------------------------------------------------------------
def rigid_parts(entry):
    """A spec's rigid parts as a list. `rigid_part` may be a single mapping or
    a list of them -- a block can pin BOTH axes at once (BlockSkin has separate
    rigidPartX and rigidPartY fields, and blitNinePatch nests them: it splits
    the centre cell by rigidPartY, then applies rigidPartX within each of the
    resulting bands). A bar that is stretched along its length but may also be
    drawn at a different thickness needs both, or the glyph smears on the axis
    that was left unpinned."""
    rp = entry.get("rigid_part")
    if not rp:
        return []
    return list(rp) if isinstance(rp, list) else [rp]


def rebase_rigid(rp, frame_px, block_size, density):
    """Convert a spec rigid_part into middle-band-relative pixels.

    BlockSkin stores `begin` in BLOCK coordinates then rebases it onto the
    stretchable middle band (`ofs -= frame.top`, clamped to the band), so we
    do exactly the same to stay in step with it.
    """
    t, r, b, l = frame_px
    sw, sh = block_size
    ofs = round(rp["begin_pts"] * density)
    length = round(rp["length_pts"] * density)
    if rp["axis"] == "y":
        mid, ofs = sh - t - b, ofs - t
    else:
        mid, ofs = sw - l - r, ofs - l
    if ofs < 0:
        length, ofs = length + ofs, 0
    if ofs + length > mid:
        length = mid - ofs
    # rigidPartX is masked by YSections (rows), rigidPartY by XSections (cols).
    names = {s.strip() for s in str(rp["sections"]).split("|")}
    if "All" in names:
        names = {"Top", "Center", "Bottom"} if rp["axis"] == "x" else {"Left", "Center", "Right"}
    return dict(axis=rp["axis"], ofs=ofs, len=max(length, 0), sections=names)


def rigid_spans(src_len, dst_len, ofs, length):
    """Split one stretchable band into (src_ofs, src_len, dst_len) runs.

    Mirrors the arithmetic in blitNinePatch: the rigid run keeps its natural
    length and whatever destination space is left over is divided between the
    two flanks in proportion to their SOURCE lengths. Note the guard -- the
    engine divides by (lead+trail), so a rigid run covering the whole band
    would divide by zero there; we degrade to a plain stretch instead.
    """
    lead_src, trail_src = ofs, src_len - ofs - length
    total_src = lead_src + trail_src
    if total_src <= 0 or length <= 0:
        return [(0, src_len, dst_len)]
    mid_dst = min(length, dst_len)
    lead_dst = (dst_len - mid_dst) * lead_src // total_src
    trail_dst = dst_len - mid_dst - lead_dst
    return [(0, lead_src, lead_dst),
            (lead_src, length, mid_dst),
            (lead_src + length, trail_src, trail_dst)]


def simulate_stretch(block, frame_px, target_px, rigids=()):
    """Stretch a single state block to `target_px` the way WonderGUI would.

    Source and destination share a px-per-pt density here, so the frame keeps
    its pixel size and only the middle bands scale.
    """
    t, r, b, l = frame_px
    sw, sh = block.size
    tw, th = target_px
    out = Image.new("RGBA", (tw, th), (0, 0, 0, 0))

    cols = [(0, l, 0, l, "Left"),
            (l, sw - l - r, l, tw - l - r, "Center"),
            (sw - r, r, tw - r, r, "Right")]
    rows = [(0, t, 0, t, "Top"),
            (t, sh - t - b, t, th - t - b, "Center"),
            (sh - b, b, th - b, b, "Bottom")]

    rx = next((r for r in rigids if r["axis"] == "x"), None)
    ry = next((r for r in rigids if r["axis"] == "y"), None)

    for sx, swid, dx, dwid, cname in cols:
        if swid <= 0 or dwid <= 0:
            continue
        for sy, shgt, dy, dhgt, rname in rows:
            if shgt <= 0 or dhgt <= 0:
                continue
            # rigidPartY subdivides the vertical middle of the named X sections
            vspans = (rigid_spans(shgt, dhgt, ry["ofs"], ry["len"])
                      if ry and rname == "Center" and cname in ry["sections"]
                      else [(0, shgt, dhgt)])
            # rigidPartX subdivides the horizontal middle of the named Y sections
            hspans = (rigid_spans(swid, dwid, rx["ofs"], rx["len"])
                      if rx and cname == "Center" and rname in rx["sections"]
                      else [(0, swid, dwid)])
            dyy = dy
            for vso, vsl, vdl in vspans:
                dxx = dx
                for hso, hsl, hdl in hspans:
                    if hsl > 0 and vsl > 0 and hdl > 0 and vdl > 0:
                        piece = block.crop((sx + hso, sy + vso,
                                            sx + hso + hsl, sy + vso + vsl))
                        if (hdl, vdl) != (hsl, vsl):
                            piece = piece.resize((hdl, vdl), Image.BILINEAR)
                        out.paste(piece, (dxx, dyy))
                    dxx += hdl
                dyy += vdl
    return out


